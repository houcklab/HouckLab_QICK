# ------------------------------------------------------------------------------------------
# markdown helpers


def md(text):
    """Escape table-breaking and emphasis characters outside `code` spans."""
    parts = str(text).split("`")
    for i, part in enumerate(parts):
        if i % 2:
            parts[i] = part.replace("|", "\\|")
        else:
            for ch in "\\|*<[]~":
                part = part.replace(ch, "\\" + ch)
            parts[i] = part
    return "`".join(parts)


def code(text):
    return "`" + str(text).replace("|", "\\|") + "`"


def names(read_by):
    return ", ".join(code(n) for n in sorted(set(read_by)))


def value(v):
    """A default as a code span; long sequences abbreviated."""
    if isinstance(v, (list, tuple)) and len(v) > 6:
        open_, close = ("[", "]") if isinstance(v, list) else ("(", ")")
        head = ", ".join(repr(x) for x in v[:3])
        return f"{code(f'{open_}{head}, ..., {v[-1]!r}{close}')} ({len(v)} values)"
    return code(repr(v))


def table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join(row) + " |" for row in rows]
    return out


