def outputs():
    """{path: (current text or None, generated text)}, newlines normalised to \\n."""
    out = {PARAMETERS_MD: (_read(PARAMETERS_MD), render_parameters())}
    for page, steps in pages().items():
        path = EXPERIMENTS / f"{page}.md"
        current = _read(path)
        if current is None:
            raise FileNotFoundError(path)
        out[path] = (current, render_page(current, steps))
    return out


def _read(path):
    return path.read_text(encoding="utf-8") if path.exists() else None


def _write(path, text):
    crlf = path.exists() and b"\r\n" in path.read_bytes()
    with open(path, "w", encoding="utf-8", newline="\r\n" if crlf else "\n") as f:
        f.write(text)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="report stale files, write nothing")
    ap.add_argument("--lint", action="store_true", help="check the hand-written pages")
    args = ap.parse_args(argv)
    if args.lint:
        errors, warns = lint_docs()
        for line in errors:
            print(f"error: {line}")
        for line in warns:
            print(f"warning: {line}")
        print(f"{len(errors)} errors, {len(warns)} warnings")
        return 1 if errors else 0
    stale = {path: new for path, (cur, new) in outputs().items() if cur != new}
    for path, text in stale.items():
        rel = path.relative_to(REPO).as_posix()
        if args.check:
            print(f"out of date: {rel}")
        else:
            _write(path, text)
            print(f"wrote {rel}")
    return 1 if args.check and stale else 0


if __name__ == "__main__":
    sys.exit(main())
