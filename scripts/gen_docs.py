_SPAN = re.compile(r"`([A-Za-z_][\w.]*)`")
_CFG_NAME = re.compile(r"(^|_)(cfg|config)$")
_PARAMS_LINK = re.compile(r"parameters\.md#([\w-]+)")


def slug(heading):
    """The anchor GitHub gives a markdown heading (no de-duplication suffix)."""
    return re.sub(r"[^\w\- ]", "", heading.strip().lower()).replace(" ", "-")


def parameters_anchors():
    """The anchors of the headings of docs/parameters.md, as render_parameters() writes it."""
    return {slug(h) for h in re.findall(r"^#+ (.+)$", render_parameters(), flags=re.M)}


def lint_pages():
    """The hand-written pages: docs/*.md but parameters.md, and concepts/, experiments/, devices/."""
    pages = [p for d in ("", "concepts", "experiments", "devices") for p in (DOCS / d).glob("*.md")]
    return sorted((p for p in pages if p != PARAMETERS_MD), key=lambda p: p.as_posix())


def hand_written(text):
    """`text` with its generated params block blanked (newlines kept, so line numbers hold)."""
    if BEGIN not in text:
        return text
    head, rest = text.split(BEGIN, 1)
    block, tail = rest.split(END, 1)
    return head + "\n" * (BEGIN + block + END).count("\n") + tail


def _call_args(text, start):
    """Top-level argument text of the call whose "(" ends at `start`: nested brackets, strings
    and # comments blanked; None when the call does not close within 4000 characters."""
    depth, quote, out, i = 1, None, [], start
    while i < len(text) and i - start < 4000:
        c = text[i]
        if quote:
            if c == quote or c == "\n":
                quote = None
            out.append(" ")
        elif c in "\"'":
            quote = c
            out.append(" ")
        elif c == "#" and text[i - 1] in " \t\n":
            j = text.find("\n", i)
            j = len(text) if j < 0 else j
            out.append(" " * (j - i))
            i = j
            continue
        elif c in "([{":
            depth += 1
            out.append(" ")
        elif c in ")]}":
            depth -= 1
            if depth == 0:
                return "".join(out)
            out.append(" ")
        else:
            out.append(c if depth == 1 and c != "`" else " ")
        i += 1
    return None


def call_keywords(name):
    """The registered keywords of the call `name` ("R.t1", "G.coherence", "Session", "Qubit");
    None for a function of R or G that is not a recipe or group builder (R.STEPS, G.resolve);
    "unknown" when R or G has no such name."""
    if name.startswith("R."):
        step = name[2:]
        if step in STEPS:
            return {p.key for p in P.entries(scope=f"recipe:{step}") if "." not in p.key}
        return None if hasattr(R, step) else "unknown"
    if name.startswith("G."):
        group = {f.__name__: g for g, f in G.BUILDERS.items()}.get(name[2:])
        if group:
            return {p.key for p in P.entries(scope=f"session:{group}")}
        return None if hasattr(G, name[2:]) else "unknown"
    if name == "Session":
        return {p.key for p in P.entries(scope="session")} | set(GROUPS) | {"device"}
    return {p.key.split(".", 1)[1] for p in P.entries("device") if p.key.startswith(name + ".")}


def keyword_names():
    """The names a keyword column may show: what a user types into a recipe, a group, Session or
    a device class (a dotted key whole or its head, a device field with or without its class),
    group names, DOC_ONLY. Not cfg keys, not legacy keys."""
    known = set(DOC_ONLY) | set(GROUPS)
    for p in P.PARAMS.values():
        if p.scope != "cfg":
            known.update((p.key, p.key.split(".")[0]))
            if p.scope == "device":
                known.add(p.key.split(".", 1)[1])
    return known


@functools.lru_cache(maxsize=None)
def scope_keywords(scope):
    """What a user types for one exact registry scope ("recipe:t1", "session:spec"): its keys, a
    dotted key ("parity_spec.gain") by its head; plus what any scoped keyword cell may also name
    (step and group names, device fields as `Class.field`, DOC_ONLY). None for an empty scope."""
    keys = {p.key.split(".", 1)[0] for p in P.entries(scope=scope)}
    if not keys:
        return None
    return frozenset(
        keys | set(STEPS) | set(GROUPS) | set(DOC_ONLY) | {p.key for p in P.entries("device")}
    )


def _row_scopes(cells, cols):
    """The scopes a row names in its "step" (recipe:<step>) and "group" (session:<group>)
    columns `cols` ({column: "recipe" or "session"})."""
    scopes = []
    for col, kind in cols.items():
        for name in _SPAN.findall(cells[col] if col < len(cells) else ""):
            if name in (STEPS if kind == "recipe" else GROUPS):
                scopes.append(f"{kind}:{name}")
    return scopes


def table_names(legacy=True):
    """Every name a parameter table may show: registered keys of any scope (and their dotted
    parts), group names, DOC_ONLY, and (legacy=True) the legacy keys that LEGACY_KEYS / G.KEYS
    map to a keyword."""
    known = set(DOC_ONLY) | set(GROUPS)
    for p in P.PARAMS.values():
        known.add(p.key)
        known.update(p.key.split("."))
    if legacy:
        for slots in R.LEGACY_KEYS.values():
            for pairs in slots.values():
                known.update(old for old, _ in pairs)
        for pairs in G.KEYS.values():
            known.update(old for old, _ in pairs)
    return known


def code_cfg_keys():
    """{literal key: sorted module paths} of cfg-dict reads and writes anywhere under qicklab:
    x[k], x.get / pop / setdefault(k) and k in x, for x a name or attribute ending in cfg or
    config."""

    def is_cfg(node):
        name = getattr(node, "id", None) or getattr(node, "attr", None) or ""
        return bool(_CFG_NAME.search(name))

    def literal(node):
        return (
            node.value if isinstance(node, ast.Constant) and isinstance(node.value, str) else None
        )

    found = {}
    for path in sorted(QICKLAB.rglob("*.py")):
        for node in ast.walk(ast.parse(path.read_text(encoding="utf-8"))):
            key = None
            if isinstance(node, ast.Subscript) and is_cfg(node.value):
                key = literal(node.slice)
            elif (
                isinstance(node, ast.Call)
                and isinstance(node.func, ast.Attribute)
                and node.func.attr in ("get", "pop", "setdefault")
                and is_cfg(node.func.value)
                and node.args
            ):
                key = literal(node.args[0])
            elif isinstance(node, ast.Compare) and any(is_cfg(c) for c in node.comparators):
                key = literal(node.left)
            if key:
                found.setdefault(key, set()).add(path.relative_to(REPO).as_posix())
    return {k: sorted(v) for k, v in found.items()}


def lint_text(text, known=None, cfg_keys=None, anchors=None, keywords=None, legacy=True):
    """(errors, warnings) of one page, each a sorted list of (line, message).

    Errors: a keyword of an R.<step>(...), G.<builder>(...), Session(...) or device-class call
    that the registry does not have under that scope; an unknown recipe or group builder; a
    first-column name of a parameter table that is not registered (nor, with legacy=True, a
    legacy key; with legacy=False a legacy key only as an alias, as in a keyword column); a name
    in a keyword column (header "Keyword(s)", "... group key", "... session values") that is not
    a keyword of its scope, unless it is a parenthesised or "legacy"-labelled alias, or a keyword
    cell that names only aliases; a name in a "<!-- lint-keywords: <scope> ... -->" paragraph that
    is not a keyword of those scopes (aliases excepted); a link to parameters.md#<anchor> whose
    heading render_parameters() does not write. The scope of a keyword column: the group of a
    "`<group>` group key" header; else, per row, the recipe / group named in the table's "step" /
    "group" column; else any keyword (keyword_names()).
    Warnings: a backticked cfg key that the code reads or writes but the registry lacks.
    """
    known = table_names(legacy) if known is None else known
    keywords = keyword_names() if keywords is None else keywords
    first_miss = "not in the registry" + ("" if legacy else " (a legacy key only as an alias)")
    cfg_keys = code_cfg_keys() if cfg_keys is None else cfg_keys
    anchors = parameters_anchors() if anchors is None else anchors
    text = hand_written(text)
    errors, warns = set(), set()

    for m in _PARAMS_LINK.finditer(text):
        if m.group(1) not in anchors:
            line = text.count("\n", 0, m.start()) + 1
            errors.add((line, f"parameters.md#{m.group(1)}: no such heading in parameters.md"))

    for m in _CALL.finditer(text):
        name, line = m.group(1), text.count("\n", 0, m.start()) + 1
        allowed = call_keywords(name)
        if allowed is None:
            continue
        if allowed == "unknown":
            errors.add((line, f"{name}(...): no such recipe or group builder"))
            continue
        for kw in _KWARG.findall(_call_args(text, m.end()) or ""):
            if kw not in allowed:
                errors.add((line, f"{name}({kw}=...): not a registered keyword"))

    # table: {column: (names allowed there, or None for the row's scopes; whether each dotted
    # part may match alone; miss)}; rows: {column: "recipe" / "session"}, the step / group columns
    alias = "a legacy or cfg key only as an alias"
    table, rows, fence = None, {}, False
    for n, line in enumerate(text.split("\n"), 1):
        if line.startswith("```"):
            fence, table = not fence, None
            continue
        if fence or not line.startswith("|"):
            table = None
            continue
        if table is None:
            raw = [c.strip() for c in line.strip().strip("|").split("|")]
            heads = [h.lower() for h in raw]
            rows = {
                i: {"step": "recipe", "group": "session"}[h]
                for i, h in enumerate(heads)
                if h in ("step", "group")
            }
            table = {}
            for i, h in enumerate(heads):
                if not _KEYWORD_HEAD.search(h):
                    continue
                group = _GROUP_HEAD.search(raw[i])
                scoped = group and scope_keywords(f"session:{group.group(1)}")
                if scoped:
                    table[i] = (
                        scoped,
                        False,
                        f"not a keyword of session:{group.group(1)} ({alias})",
                    )
                else:
                    table[i] = (None if rows else keywords, False, f"not a keyword ({alias})")
            if heads[0] in _TABLE_FIRST and (
                heads[0] == "name (legacy key)" or any(h in _TABLE_COLS for h in heads)
            ):
                table.setdefault(0, (known, True, first_miss))
            continue
        if not table or set(line) <= set("|-: "):
            continue
        cells = line.strip().strip("|").split("|")
        for col, (allowed, by_part, miss) in table.items():
            raw_cell = cells[col] if col < len(cells) else ""
            cell = _ALIAS.sub("", raw_cell)
            if allowed is None:
                scopes = _row_scopes(cells, rows)
                allowed = frozenset().union(*map(scope_keywords, scopes)) if scopes else keywords
                if scopes:
                    miss = f"not a keyword of {' / '.join(scopes)} ({alias})"
            if allowed is not known and _SPAN.findall(raw_cell) and not _SPAN.findall(cell):
                errors.add((n, "keyword cell names only an alias, no keyword"))
            for name in _SPAN.findall(cell):
                if not all(part in allowed for part in (name.split(".") if by_part else [name])):
                    errors.add((n, f"parameter table names `{name}`: {miss}"))

    # "<!-- lint-keywords: <scope> ... -->": the next paragraph names keywords of those scopes
    lines = text.split("\n")
    for n, line in enumerate(lines, 1):
        mark = _MARK.match(line)
        if not mark:
            continue
        scopes = mark.group(1).split()
        bad = [s for s in scopes if scope_keywords(s) is None]
        if bad or not scopes:
            errors.add((n, f"lint-keywords: no such registry scope {' '.join(bad)}".rstrip()))
            continue
        allowed = frozenset().union(*map(scope_keywords, scopes))
        start = n
        while start < len(lines) and not lines[start].strip():
            start += 1
        end = start
        while end < len(lines) and lines[end].strip():
            end += 1
        if start == end:
            errors.add((n, "lint-keywords: no paragraph follows"))
            continue
        para = "\n".join(lines[start:end])
        para = _ALIAS.sub(lambda m: re.sub(r"[^\n]", " ", m.group()), para)
        for k, para_line in enumerate(para.split("\n"), start + 1):
            for name in _SPAN.findall(para_line):
                if name not in allowed:
                    errors.add((k, f"`{name}`: not a keyword of {' / '.join(scopes)}"))

    for n, line in enumerate(text.split("\n"), 1):
        for name in _SPAN.findall(line):
            if name in cfg_keys and name not in known:
                where = ", ".join(cfg_keys[name][:2])
                warns.add((n, f"`{name}`: a cfg key ({where}) the registry lacks"))
    return sorted(errors), sorted(warns)


def lint_docs():
    """(errors, warnings) over lint_pages(), as "docs/<page>:<line>: <message>" strings. Only
    the step pages (docs/experiments/), whose Parameters sections describe the legacy dicts,
    may give a bare legacy key in a parameter table's first column."""
    cfg_keys, anchors, keywords = code_cfg_keys(), parameters_anchors(), keyword_names()
    known = {legacy: table_names(legacy) for legacy in (True, False)}
    errors, warns = [], []
    for path in lint_pages():
        rel = path.relative_to(REPO).as_posix()
        legacy = path.parent == EXPERIMENTS
        text = path.read_text(encoding="utf-8")
        e, w = lint_text(text, known[legacy], cfg_keys, anchors, keywords, legacy)
        errors += [f"{rel}:{n}: {msg}" for n, msg in e]
        warns += [f"{rel}:{n}: {msg}" for n, msg in w]
    return errors, warns


