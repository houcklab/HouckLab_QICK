# tables

KW_HEADER = ("Keyword", "Default", "Units", "Meaning", "Notes")


def keyword_rows(entries):
    rows = []
    for p in entries:
        d, notes = default_of(p)
        rows.append((code(p.key), d, md(p.units), md(p.meaning), notes))
    return rows


def recipe_table(step):
    return table(KW_HEADER, keyword_rows(recipe_entries(step)))


def recipe_summary(step, docs, see):
    """One line: the recipe, its regime and run function, its session groups, then `see`.

    `docs` is the path prefix from the page to docs/ ("" or "../").
    """
    s = STEPS[step]()
    groups = step_groups(step)
    grp = ", ".join(code(g) for g in groups) if groups else "none"
    return (
        f"Recipe: {code(f'R.{step}(...)')} (`qicklab.runs.recipes`, `help(R.{step})`): "
        f"regime [{s.regime}]({docs}concepts/config_regimes.md#{REGIME_ANCHOR[s.regime]}), "
        f"calls {code(s.fn.__name__)}, session groups {grp} "
        f"([shared groups]({docs}running_a_session.md#shared-groups)). {see}"
    )


def _setter(p):
    family = P.scope_family(p.scope)
    if family == "device":
        cls, field = p.key.split(".", 1)
        return f"{code(f'{cls}({field}=...)')} in `devices/<NAME>.py`"
    if p.scope == "session":
        return code(f"Session({p.key}=...)")
    if p.scope.startswith("session:"):
        group = p.scope.split(":", 1)[1]
        return code(f"Session({group}=G.{_builder(group).__name__}({p.key}=...))")
    return code(f"R.{p.scope.split(':', 1)[1]}({p.key}=...)")


def knob_rows():
    rows = []
    for label, scope, key in KNOBS:
        p = P.PARAMS[(key, scope)]
        d, _ = default_of(p)
        if d == REQUIRED and P.scope_family(scope) == "device":
            d = "per device"
        meaning = p.meaning + (f" ({p.notes})" if p.notes else "")
        rows.append((md(label), _setter(p), d, md(p.units), md(meaning)))
    return rows


