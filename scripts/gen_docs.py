def page_block(steps):
    out = [BEGIN, "", GENERATED, ""]
    for step in steps:
        see = f"Every parameter: [parameters.md](../parameters.md#r{step})."
        rows = recipe_table(step)
        out += [recipe_summary(step, "../", see), ""]
        n = len(rows) - 2
        if n > COLLAPSE_ROWS:
            out += [
                f"<details><summary>The {n} keywords of R.{step}</summary>",
                "",
                *rows,
                "",
                "</details>",
                "",
            ]
        else:
            out += [*rows, ""]
    out.append(END)
    return "\n".join(out)


def render_page(text, steps):
    """`text` with its params block (or, the first time, its "Recipe:" line) regenerated."""
    block = page_block(steps)
    if text.count(BEGIN) == 1 and text.count(END) == 1:
        head, rest = text.split(BEGIN)
        _, tail = rest.split(END)
        return head + block + tail
    if BEGIN in text or END in text:
        raise ValueError("unbalanced params markers")
    lines = text.split("\n")
    hits = [i for i, line in enumerate(lines) if line.startswith("Recipe: `R.")]
    if len(hits) != 1:
        raise ValueError("no params markers and no single 'Recipe: `R.' line to replace")
    lines[hits[0]] = block
    return "\n".join(lines)


