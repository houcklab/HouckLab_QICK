# ordering


def device_entries(cls):
    order = {f.name: i for i, f in enumerate(dataclasses.fields(cls))}
    rows = [p for p in P.entries("device") if p.key.split(".", 1)[0] == cls.__name__]
    return sorted(rows, key=lambda p: (order.get(p.key.split(".", 1)[1], len(order)), p.key))


def signature_order(entries, keywords):
    """Entries in signature order; "<kw>.<key>" rows follow their keyword in dict order."""
    by_key = {p.key: p for p in entries}
    out = []
    subs = _zsp_subdefaults()
    for kw in keywords:
        if kw in by_key:
            out.append(by_key.pop(kw))
        for sub in subs.get(kw, ()):
            if f"{kw}.{sub}" in by_key:
                out.append(by_key.pop(f"{kw}.{sub}"))
    if by_key:
        raise ValueError(f"registry entries not in the signature: {sorted(by_key)}")
    return out


def recipe_entries(step):
    return signature_order(
        P.entries("recipe", f"recipe:{step}"), inspect.signature(STEPS[step]).parameters
    )


def group_entries(group):
    return signature_order(
        P.entries("session", f"session:{group}"), inspect.signature(_builder(group)).parameters
    )


def session_entries():
    fields = [f.name for f in dataclasses.fields(Session) if f.name not in GROUPS]
    return signature_order(P.entries("session", "session"), fields)


def cfg_entries():
    return sorted(P.entries("cfg"), key=lambda p: (p.key.lower(), p.key, p.scope))


def step_groups(step):
    """The session groups a step reads by name, in GROUPS order.

    The union of: its Step.needs group slots; the groups whose registry read_by names its run
    function (e.g. charge_transmission_sweep reads the transmission and charge groups itself);
    the groups its `None` defaults fall back to ("None: the <group> group's <key>" notes); for
    a regime-B step, the groups the regime-B config builder reads (the single_shot group the
    config is rebuilt from). Not listed: the regime-A base config that build_context makes
    from the transmission, spec, charge and tones groups, which every regime-A step runs on.
    """
    s = STEPS[step]()
    readers = {s.fn.__name__}
    if s.regime == "B":
        readers.add("rebuild_singleshot_config")
    named = {g for g in s.needs if g in GROUPS}
    for group in GROUPS:
        if any(readers & set(p.read_by) for p in P.entries("session", f"session:{group}")):
            named.add(group)
    for p in P.entries("recipe", f"recipe:{step}"):
        m = _AUTO_GROUP_NOTE.match(p.notes)
        if m:
            named.add(m.group(1))
    unknown = named - set(GROUPS)
    if unknown:
        raise ValueError(f"{step}: notes name unknown session groups {sorted(unknown)}")
    return [g for g in GROUPS if g in named]


def pages():
    """{page: [step, ...]} in STEPS order."""
    out = {}
    for step in STEPS:
        out.setdefault(PAGE_OF.get(step, step), []).append(step)
    return out


