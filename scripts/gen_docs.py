# defaults, from the code

REQUIRED = "required"


def _signature_defaults(fn):
    return {
        name: (REQUIRED if p.default is inspect.Parameter.empty else p.default)
        for name, p in inspect.signature(fn).parameters.items()
    }


def _field_default(f):
    if f.default is not dataclasses.MISSING:
        return f.default
    if f.default_factory is not dataclasses.MISSING:
        return f.default_factory()
    return REQUIRED


def _builder(group):
    return G.BUILDERS[group]


def group_default(group, key):
    return _signature_defaults(_builder(group))[key]


def _zsp_subdefaults():
    """{keyword: {legacy key: default}} of zero_span_parity's dict keywords."""
    legacy_of = dict(
        (kw, legacy) for legacy, kw in R.LEGACY_KEYS["zero_span_parity"]["zero_span_params"]
    )
    return {
        kw: R.ZSP_SUBDICTS[legacy] for kw, legacy in legacy_of.items() if legacy in R.ZSP_SUBDICTS
    }


def default_of(p):
    """(default cell, notes cell) of a registry entry."""
    family = P.scope_family(p.scope)
    notes = p.notes
    if family == "device":
        cls, field = p.key.split(".", 1)
        f = {f.name: f for f in dataclasses.fields(getattr(D, cls))}[field]
        d = _field_default(f)
    elif p.scope == "session":
        d = _field_default({f.name: f for f in dataclasses.fields(Session)}[p.key])
    elif p.scope.startswith("session:"):
        d = group_default(p.scope.split(":", 1)[1], p.key)
    elif family == "recipe":
        step = p.scope.split(":", 1)[1]
        if "." in p.key:
            kw, sub = p.key.split(".", 1)
            d = _zsp_subdefaults()[kw][sub]
        else:
            d = _signature_defaults(STEPS[step])[p.key]
            if step == "zero_span_parity" and p.key in _zsp_subdefaults():
                return "keys below", md(notes)
            m = _AUTO_GROUP_NOTE.match(notes)
            if d is None and m:
                group, key = m.groups()
                gd = group_default(group, key)
                if gd is None:
                    gnotes = P.PARAMS[(key, f"session:{group}")].notes
                    return f"{code(None)} ({group} group)", md(gnotes)
                return f"{code(None)} ({group} group: {value(gd)})", ""
    else:
        return "", md(notes)
    cell = REQUIRED if d is REQUIRED else value(d)
    return cell, md(notes)


