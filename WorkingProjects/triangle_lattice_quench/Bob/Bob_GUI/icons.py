def svg(name: str, color: str = "#FFFFFF", stroke: float = 2.0) -> str:
    return ('<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" '
            f'stroke="{color}" stroke-width="{stroke}" stroke-linecap="round" stroke-linejoin="round">'
            f'{PATHS[name]}</svg>')


@lru_cache(maxsize=256)
def pixmap(name: str, color: str = "#FFFFFF", size: int = 16) -> QPixmap:
    renderer = QSvgRenderer(QByteArray(svg(name, color).encode()))
    pm = QPixmap(size * 2, size * 2)
    pm.fill(Qt.transparent)
    p = QPainter(pm)
    renderer.render(p, QRectF(0, 0, size * 2, size * 2))
    p.end()
    pm.setDevicePixelRatio(2.0)
    return pm


def icon(name: str, color: str = "#FFFFFF", size: int = 16) -> QIcon:
    return QIcon(pixmap(name, color, size))
